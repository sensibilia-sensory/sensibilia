// Laboratory certificate authority. `-PlabCa=<root.crt>` (path relative to android/, or
// absolute) bakes the laboratory's root certificate into this APK as a trust anchor, so tablets need no
// certificate installed in Settings. The CA is public data, not a secret, but it is specific to one
// laboratory: the file is not committed and the APK built from it is a per-laboratory artefact.
// Without the property the app trusts system and user-installed certificates, as before.
val labCaFile = providers.gradleProperty("labCa").map { rootProject.file(it) }
val labCaRes = layout.buildDirectory.dir("generated/labCa/res")

val generateLabCa by tasks.registering {
    inputs.files(providers.provider { listOfNotNull(labCaFile.orNull) })
    outputs.dir(labCaRes)
    doLast {
        val res = labCaRes.get().asFile
        res.deleteRecursively()
        val xml = File(res, "xml").apply { mkdirs() }
        val ca = labCaFile.orNull
        val anchors =
            if (ca != null) {
                require(ca.isFile) { "labCa file not found: $ca" }
                require(ca.readText().contains("BEGIN CERTIFICATE")) {
                    "labCa must be a PEM certificate (-----BEGIN CERTIFICATE-----): $ca"
                }
                File(res, "raw").apply { mkdirs() }
                ca.copyTo(File(res, "raw/lab_ca.crt"), overwrite = true)
                """<certificates src="system" />
            <certificates src="@raw/lab_ca" />"""
            } else {
                """<certificates src="system" />
            <certificates src="user" />"""
            }
        File(xml, "network_security_config.xml").writeText(
            """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by build.gradle.kts (generateLabCa). HTTPS only. With -PlabCa the laboratory root is a
     trust anchor and user-installed certificates are not trusted; without it, certificates staff
     installed on the tablet are, so a laboratory or test authority works once its root is installed. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false">
        <trust-anchors>
            $anchors
        </trust-anchors>
    </base-config>
</network-security-config>
"""
        )
    }
}

android.sourceSets.getByName("main").res.srcDir(labCaRes)
tasks.named("preBuild") { dependsOn(generateLabCa) }

